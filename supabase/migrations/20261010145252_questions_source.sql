-- Stable IDs are retained. A conflicting INSERT receives a fresh ID; UPDATE never renumbers silently.
create function public.reassign_conflicting_question_id() returns trigger language plpgsql security definer set search_path='' as $$
begin
 perform pg_advisory_xact_lock(741903205);
 while exists(select 1 from public.questions where id=new.id) loop
   new.id=nextval(pg_get_serial_sequence('public.questions','id'));
 end loop;
 return new;
end $$;
revoke all on function public.reassign_conflicting_question_id() from public,anon,authenticated;
create trigger trg_reassign_question_id before insert on public.questions for each row execute function public.reassign_conflicting_question_id();

