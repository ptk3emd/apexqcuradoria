create function public.normalize_competencies(value text) returns text[] language plpgsql immutable set search_path='' as $$
declare parts text[]; parsed jsonb;
begin
 if value is null then return null; end if;
 if btrim(value)='' then return array[]::text[]; end if;
 if left(btrim(value),1)='[' then
   begin parsed=value::jsonb; exception when invalid_text_representation then parsed=null; end;
 end if;
 if jsonb_typeof(parsed)='array' then select array_agg(v) into parts from jsonb_array_elements_text(parsed) v;
 else parts=regexp_split_to_array(value,'[,;|]+'); end if;
 return (select coalesce(array_agg(v order by v),array[]::text[]) from (select distinct lower(btrim(x)) v from unnest(parts) x where btrim(x)<>'') t);
end $$;
revoke all on function public.normalize_competencies(text) from public,anon;
grant execute on function public.normalize_competencies(text) to authenticated;
