import type {Question, AuditLogItem} from '../types/question';
import {generateCorrectedQuestionsSql, isCorrectedQuestion, sqlText} from './correctedQuestionsSql';

const comment = (value:string) => value.replace(/[\r\n\u0000]/g, ' ');
export const pgEscape = (value:string | null | undefined) => sqlText(value ?? null);

// Every export is rebuilt from confirmed question content, never persisted SQL logs.
export function generateSqlForQuestion(q:Question, _curatorName='Curador ApexMed'):string {
  if (!isCorrectedQuestion(q)) return '-- Nenhuma correção de conteúdo para exportar. Status de curadoria não pertence a public.questions.';
  const result = generateCorrectedQuestionsSql([q]);
  return result.errors.length ? result.errors.map(error => '-- SQL não gerado: '+comment(error)).join('\n') : result.sql;
}

export function generateProgressiveSqlScript(_logs:AuditLogItem[], questions:Question[], regexFilter?:string):string {
  let selected = questions;
  if (regexFilter?.trim()) {
    try {
      const regex = new RegExp(regexFilter, 'i');
      selected = questions.filter(q => regex.test(q.id) || regex.test(generateSqlForQuestion(q)));
    } catch {return '-- SQL não gerado: filtro de expressão regular inválido.';}
  }
  const result = generateCorrectedQuestionsSql(selected);
  return result.errors.length ? result.errors.map(error => '-- SQL não gerado: '+comment(error)).join('\n') : result.sql;
}

